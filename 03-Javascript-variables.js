// String
let firstname = "Sushant";
let lastname = "Dhakal";

// Number
let age = 10;
let price = 99.99;

// Boolean
let isStudent = true;
let hasGraduated = false;

// Undefined
let message;

// Null
let middleName = null;

// Array
let subjects = ["Math", "Science", "English"];

// Object
let student = {
  name: "Sushant Dhakal",
  age: 10,
  isStudent: true
};

// Constant
const nation = "Nepal";

// Symbol
let uniqueId = Symbol("id");

// BigInt
let bigNumber = 123456789012345678901234567890n;

// Printing values
console.log("First Name:", firstname);
console.log("Last Name:", lastname);
console.log("Age:", age);
